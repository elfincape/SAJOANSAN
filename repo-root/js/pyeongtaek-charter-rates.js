const byName = new Map(rows.map(row => [row.name, row]));

export function charterRegion(address) {
  const text = String(address).trim();
  const token = name => new RegExp(`(?:^|\\s)${name}(?:특별자치시|광역시|특별시|시|군|구|읍|면|동)?(?=\\s|$|[,()])`).test(text);
  let name = '';
  if (/(?:^|\s)서울(?:특별시|시)?(?=\s|$)/.test(text)) {
    const district = text.match(/(?:^|\s)([가-힣]+구)(?=\s|$)/)?.[1] || '';
    name = district === '중구' ? district : district.replace(/구$/, '');
    name ||= '서울';
    return { name, rate: byName.get(name) || null };
  }
  if (/(?:^|\s)광주광역시(?=\s|$)/.test(text)) name = '전광주';
  // More specific rate districts precede their parent city.
  if (!name && /인천(?:국제)?공항/.test(text)) name = '인천공항';
  if (!name) name = ['강화','부평','동탄','송탄','포승','진접','화도','하양'].find(token) || '';
  if (!name) name = rows.find(row => row.area !== '서울특별시' && token(row.name))?.name || '';
  if (!name) name = text.match(/(?:^|\s)([가-힣]+?)(?:특별자치시|광역시|특별시|시|군)(?=\s|$|[,()])/)?.[1] || '';
  return { name, rate: byName.get(name) || null };
}
